#!/usr/bin/env node
/**
 * Generates docs/SELECTOR-CONTRACT.md from the screen/page objects so the test-ID contract
 * handed to the mobile and web developers never drifts from what the tests actually use.
 *   node scripts/extract-selectors.js
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : p.endsWith('.ts') ? [p] : [];
  });
}

const normalise = (s) => s.replace(/\$\{([^}]+)\}/g, '{$1}');

// Mobile: string / template literals shaped like module.screen.element passed to screen helpers.
const MOBILE_ID = /[`'"]((?:[a-z][A-Za-z0-9]*)(?:\.(?:[A-Za-z0-9]+|\$\{[^}]+\}))+)[`'"]/g;
const mobileModules = new Set(['auth', 'home', 'grow', 'borrow', 'wallet', 'kyc', 'rwin', 'reap', 'rtn', 'nano', 'payday', 'personal', 'publicSector', 'common', 'notifications', 'search', 'loan', 'loans']);

const mobile = new Map();
for (const file of walk(path.join(root, 'mobile/screens'))) {
  const src = fs.readFileSync(file, 'utf8');
  for (const m of src.matchAll(MOBILE_ID)) {
    const id = normalise(m[1]);
    const mod = id.split('.')[0];
    if (!mobileModules.has(mod) || /\.(ts|js|json)$/.test(id)) continue;
    if (!mobile.has(mod)) mobile.set(mod, new Set());
    mobile.get(mod).add(id);
  }
}

// Admin: getByTestId('...') in page objects.
const ADMIN_ID = /getByTestId\(\s*[`'"]([^`'"]+)[`'"]\s*\)/g;
const admin = new Map();
for (const file of walk(path.join(root, 'admin/pages'))) {
  const src = fs.readFileSync(file, 'utf8');
  const page = path.basename(file, '.ts');
  for (const m of src.matchAll(ADMIN_ID)) {
    if (!admin.has(page)) admin.set(page, new Set());
    admin.get(page).add(normalise(m[1]));
  }
}

let out = `# Selector contract\n\n_Generated by \`node scripts/extract-selectors.js\`. Do not edit by hand._\n\n`;
out += `**Audience:** mobile and web developers. Every element the automation touches is addressed by a stable test ID.\n\n`;
out += `- **Mobile:** set \`testID\` (React Native), \`Key\` / \`Semantics(identifier:)\` (Flutter), or \`accessibilityIdentifier\` / \`resource-id\` (native) to the exact ID below. \`{i}\` means a zero-based index; \`{x}\` means the value named.\n`;
out += `- **Inline errors** use the input's ID plus \`.error\`, for example \`rwin.booking.deposit.input.error\`.\n`;
out += `- **Admin web:** add \`data-testid\`. Buttons, menu items, tabs and dialogs are located by accessible role and name taken from the PRD action names, so keep those labels in sync with the PRD.\n\n`;

const total = [...mobile.values()].reduce((n, s) => n + s.size, 0);
out += `## Mobile app (${total} IDs)\n\n`;
for (const [mod, ids] of [...mobile.entries()].sort()) {
  out += `### ${mod} (${ids.size})\n\n`;
  out += [...ids].sort().map((i) => `- \`${i}\``).join('\n') + '\n\n';
}
out += `## Admin portal\n\n`;
for (const [page, ids] of [...admin.entries()].sort()) {
  out += `### ${page}\n\n` + [...ids].sort().map((i) => `- \`${i}\``).join('\n') + '\n\n';
}

fs.writeFileSync(path.join(root, 'docs/SELECTOR-CONTRACT.md'), out);
console.log(`Wrote docs/SELECTOR-CONTRACT.md — ${total} mobile IDs across ${mobile.size} modules, ${[...admin.values()].reduce((n, s) => n + s.size, 0)} admin test IDs`);
